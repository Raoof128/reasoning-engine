//! The twenty tool definitions: names, descriptions and input schemas in
//! Python's registration order, with the JSON Schema pydantic generates for
//! each signature (tested against `tests/fixtures/mcp_tools.json`).

use serde_json::{Map, Value, json};

/// A parameter's Python type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// `str`
    Str,
    /// `int`
    Int,
    /// `float`
    Float,
    /// `bool` (Rust-only parameters; Python's tools have none)
    Bool,
    /// `list[str] | str`
    StrListOrStr,
    /// `list[dict] | str`
    DictListOrStr,
    /// `object | None`
    AnyOrNull,
}

/// One parameter.
#[derive(Debug, Clone, Copy)]
pub struct Param {
    /// Python parameter name.
    pub name: &'static str,
    /// Python type.
    pub kind: Kind,
    /// Default, as JSON text; `None` means required.
    pub default: Option<&'static str>,
}

/// One tool.
#[derive(Debug, Clone, Copy)]
pub struct ToolSpec {
    /// Tool name.
    pub name: &'static str,
    /// The Python docstring.
    pub description: &'static str,
    /// Parameters in signature order.
    pub params: &'static [Param],
    /// Never writes state (the plan's `readOnlyHint` list).
    pub read_only: bool,
}

const fn req(name: &'static str, kind: Kind) -> Param {
    Param {
        name,
        kind,
        default: None,
    }
}

const fn opt(name: &'static str, kind: Kind, default: &'static str) -> Param {
    Param {
        name,
        kind,
        default: Some(default),
    }
}

