/// Pydantic's field title: `field_name.replace("_", " ").title()`.
fn title(name: &str) -> String {
    name.split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first
                    .to_uppercase()
                    .chain(chars.flat_map(char::to_lowercase))
                    .collect()
            })
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn property(param: &Param) -> Value {
    let mut schema = match param.kind {
        Kind::Str => json!({"type": "string"}),
        Kind::Int => json!({"type": "integer"}),
        Kind::Float => json!({"type": "number"}),
        Kind::Bool => json!({"type": "boolean"}),
        Kind::StrListOrStr => {
            json!({"anyOf": [{"items": {"type": "string"}, "type": "array"}, {"type": "string"}]})
        }
        Kind::DictListOrStr => json!({"anyOf": [
            {"items": {"additionalProperties": true, "type": "object"}, "type": "array"},
            {"type": "string"},
        ]}),
        Kind::AnyOrNull => json!({"anyOf": [{}, {"type": "null"}]}),
    };
    let map = schema.as_object_mut().expect("object literal");
    if let Some(default) = param.default {
        map.insert(
            "default".into(),
            serde_json::from_str(default).expect("valid default literal"),
        );
    }
    map.insert("title".into(), title(param.name).into());
    schema
}

/// The tool's `inputSchema`, as pydantic would generate it.
#[must_use]
pub fn input_schema(spec: &ToolSpec) -> Map<String, Value> {
    let properties: Map<String, Value> = spec
        .params
        .iter()
        .map(|p| (p.name.to_string(), property(p)))
        .collect();
    let required: Vec<&str> = spec
        .params
        .iter()
        .filter(|p| p.default.is_none())
        .map(|p| p.name)
        .collect();
    let mut schema = Map::new();
    schema.insert("properties".into(), Value::Object(properties));
    if !required.is_empty() {
        schema.insert("required".into(), json!(required));
    }
    schema.insert("title".into(), format!("{}Arguments", spec.name).into());
    schema.insert("type".into(), "object".into());
    schema
}

/// Look a tool up by name.
#[must_use]
pub fn find(name: &str) -> Option<&'static ToolSpec> {
    TOOLS.iter().find(|t| t.name == name)
}

